//! The Rust emitter: the typed testbench API of one model.
//!
//! The output is meant for `include!` in the user's crate, so it uses only fully
//! qualified paths (`::core::..`, `::simjig::__private::..`) and introduces only the
//! items the design names, plus `Dut`. The runtime items it expects are listed in
//! `docs/notes/codegen.md` ("The `__private` contract").
//!
//! The file ends with the model glue: one `dut_model!` invocation naming the model's C side
//! (prefix, vtable symbol, time precision), which implements `simjig::DutModel` for `Dut`.
//! The `unsafe extern` declaration lives inside that macro, so the file compiles in a crate
//! with `#![forbid(unsafe_code)]` (the lint does not fire on code expanded from another
//! crate's `macro_rules!`).

mod items;

use svtypes::ir::Storage;

use super::writer::Writer;
use super::{
    Access, Bundle, ConstGroup, ConstValue, DutField, Lowered, RustType, Signal, SignalTarget,
};

/// The runtime's hidden module.
pub(crate) const RT: &str = "::simjig::__private";
/// The bit-vector crate, as re-exported by the runtime.
pub(crate) const BITS: &str = "::simjig::__private::bits";

/// The fully qualified path of the primitive type `name`. Generated code spells every
/// name it uses by absolute path, because it is spliced into a user module whose glob
/// imports would shadow the prelude (and even primitive types).
pub(crate) fn prim(name: &str) -> String {
    format!("::core::primitive::{name}")
}

/// A `#[derive(..)]` of standard traits, each by absolute path (see [`prim`]).
pub(crate) fn derive(traits: &[&str]) -> String {
    let paths: Vec<String> = traits
        .iter()
        .map(|t| {
            let module = match *t {
                "Clone" => "clone",
                "Copy" => "marker",
                "PartialEq" | "Eq" => "cmp",
                "Hash" => "hash",
                "Default" => "default",
                "Debug" => "fmt",
                other => unreachable!("no path for derive `{other}`"),
            };
            format!("::core::{module}::{t}")
        })
        .collect();
    format!("#[derive({})]", paths.join(", "))
}

/// What the Rust bindings need besides the lowering: the model's C side, which only the
/// build pipeline knows.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RustOptions {
    /// The Verilator `--prefix` of the model; its shim exports `simjig_vtable_<prefix>`.
    pub prefix: String,
    /// The design's time precision as a power of ten seconds (`-12` is 1 ps): the unit of
    /// the simulation's ticks.
    pub precision_exponent: i8,
    /// C names of the DPI-C imports implemented in Rust (see `emit_dpi`), in IR order; the
    /// runtime gives only models with some a DPI scope around each eval.
    pub dpi_imports: Vec<String>,
}

/// Emits the Rust source for `lowered`, loading the model `opts` names.
#[must_use]
pub fn emit_rust(lowered: &Lowered, opts: &RustOptions) -> String {
    let mut w = Writer::new("    ");
    w.line(format!(
        "// @generated by simjig-build from the IR of `{}` ({}). Do not edit.",
        lowered.top, lowered.producer
    ));
    for item in &lowered.items {
        w.line("");
        items::emit_item(&mut w, item);
    }
    for group in &lowered.packages {
        w.line("");
        emit_package(&mut w, group);
    }
    for bundle in &lowered.bundles {
        w.line("");
        emit_bundle(&mut w, bundle);
    }
    w.line("");
    emit_dut(&mut w, lowered);
    w.line("");
    emit_model_glue(&mut w, opts);
    w.finish()
}

/// `impl DutModel for Dut`, through the runtime's macro (see the module docs).
fn emit_model_glue(w: &mut Writer, opts: &RustOptions) {
    w.open(format!("{RT}::dut_model!("));
    w.line("Dut,");
    w.line(format!("prefix = {:?},", opts.prefix));
    w.line(format!(
        "symbol = {:?},",
        format!("simjig_vtable_{}", opts.prefix)
    ));
    w.line(format!("precision_exponent = {},", opts.precision_exponent));
    if !opts.dpi_imports.is_empty() {
        let names: Vec<String> = opts.dpi_imports.iter().map(|n| format!("{n:?}")).collect();
        w.line(format!("dpi_imports = [{}],", names.join(", ")));
    }
    w.close(");");
}

/// The Rust spelling of `ty`.
pub(crate) fn render(ty: &RustType) -> String {
    match ty {
        RustType::Bit => format!("{BITS}::Bit"),
        RustType::Bits(n) => format!("{BITS}::Bits<{n}>"),
        RustType::WideBits { width, words } => format!("{BITS}::WideBits<{width}, {words}>"),
        RustType::Named(name) => name.clone(),
        RustType::Array(elem, len) => format!("[{}; {len}]", render(elem)),
    }
}

/// A const expression of `base` (a [`RustType::Bit`] or [`RustType::Bits`]) holding `value`.
pub(crate) fn base_value(base: &RustType, value: u128) -> String {
    match base {
        RustType::Bit => format!("{BITS}::Bit::new({})", value == 1),
        RustType::Bits(n) => format!("{BITS}::Bits::<{n}>::new_truncating({})", hex(value)),
        other => format!("{}::default()", render(other)),
    }
}

/// `digits` with `_` every `group` digits from the right, as clippy's `unreadable_literal`
/// asks of long literals; a leading `-` is kept.
fn grouped(digits: &str, group: usize) -> String {
    let (sign, digits) = digits.strip_prefix('-').map_or(("", digits), |d| ("-", d));
    if digits.len() <= 4 || !digits.chars().all(|c| c.is_ascii_hexdigit()) {
        return format!("{sign}{digits}");
    }
    let mut out = String::new();
    for (i, c) in digits.chars().enumerate() {
        if i > 0 && (digits.len() - i) % group == 0 {
            out.push('_');
        }
        out.push(c);
    }
    format!("{sign}{out}")
}

/// A hex literal, grouped by 4 digits.
pub(crate) fn hex(value: u128) -> String {
    format!("0x{}", grouped(&format!("{value:x}"), 4))
}

/// The Rust type of Verilator storage (the `Packed::Raw` contract).
pub(crate) fn raw_type(storage: &Storage) -> String {
    match storage {
        Storage::CData => prim("u8"),
        Storage::SData => prim("u16"),
        Storage::IData => prim("u32"),
        Storage::QData => prim("u64"),
        Storage::VlWide { words } => format!("[{}; {words}]", prim("u32")),
        Storage::VlUnpacked { elem, len } => format!("[{}; {len}]", raw_type(elem)),
    }
}

/// `{RT}::Storage` as a const expression.
fn storage_meta(storage: &Storage) -> String {
    match storage {
        Storage::CData => format!("{RT}::Storage::CData"),
        Storage::SData => format!("{RT}::Storage::SData"),
        Storage::IData => format!("{RT}::Storage::IData"),
        Storage::QData => format!("{RT}::Storage::QData"),
        Storage::VlWide { words } => format!("{RT}::Storage::VlWide {{ words: {words} }}"),
        Storage::VlUnpacked { elem, len } => {
            format!(
                "{RT}::Storage::VlUnpacked {{ elem: &{}, len: {len} }}",
                storage_meta(elem)
            )
        }
    }
}

/// The handle type and the `Binder` method for an access kind.
fn handle(access: Access) -> (&'static str, &'static str) {
    match access {
        Access::In => ("In", "input"),
        Access::Out => ("Out", "output"),
        Access::InOut => ("InOut", "inout"),
        Access::PublicRd => ("PublicRd", "public_rd"),
        Access::PublicRw => ("PublicRw", "public_rw"),
    }
}

/// A Rust literal for a [`ConstValue`], and its type; `scope` prefixes generated types.
fn const_parts(value: &ConstValue, scope: &str) -> (String, String) {
    match value {
        ConstValue::Int { ty, value } => (prim(ty), grouped(value, 3)),
        ConstValue::Wide { width, words } => {
            let ty = format!("{BITS}::WideBits<{width}, {}>", words.len());
            let list: Vec<String> = words.iter().map(|w| hex(u128::from(*w))).collect();
            let expr = format!(
                "{BITS}::WideBits::<{width}, {}>::from_words([{}])",
                words.len(),
                list.join(", ")
            );
            (ty, expr)
        }
        ConstValue::Enum { ty, base, value } => (
            format!("{scope}{ty}"),
            format!("{scope}{ty}::from_bits({})", base_value(base, *value)),
        ),
        ConstValue::Str(s) => (format!("&{}", prim("str")), format!("{s:?}")),
        ConstValue::Real(text) => (prim("f64"), text.clone()),
    }
}

fn emit_package(w: &mut Writer, group: &ConstGroup) {
    w.line(format!(
        "/// Parameters of SystemVerilog package `{}`.",
        group.package
    ));
    w.open(format!("pub mod {} {{", group.module));
    for c in &group.consts {
        let (ty, expr) = const_parts(&c.value, "super::");
        w.line(format!("/// `{}`.", c.sv_name));
        w.line(format!("pub const {}: {ty} = {expr};", c.name));
    }
    w.close("}");
}

fn emit_bundle(w: &mut Writer, bundle: &Bundle) {
    w.line(format!(
        "/// Interface modport `{}`, as seen by the testbench.",
        bundle.sv_name
    ));
    w.line(derive(&["Clone", "Copy", "Debug"]));
    w.open(format!("pub struct {} {{", bundle.name));
    for m in &bundle.members {
        let (h, _) = handle(m.access);
        w.line(format!("/// `{}`.", m.sv_name));
        w.line(format!("pub {}: {RT}::{h}<{}>,", m.name, render(&m.ty)));
    }
    w.close("}");
    w.line("");
    w.open(format!("impl {} {{", bundle.name));
    w.line("#[doc(hidden)]");
    w.open(format!(
        "pub fn __bind(binder: &mut impl {RT}::Binder, signals: &'static [{RT}::SignalMeta]) -> Self {{"
    ));
    w.open("Self {");
    for (i, m) in bundle.members.iter().enumerate() {
        let (_, method) = handle(m.access);
        w.line(format!(
            "{}: {RT}::Binder::{method}(binder, &signals[{i}]),",
            m.name
        ));
    }
    w.close("}");
    w.close("}");
    w.close("}");
}

fn signal_doc(s: &Signal) -> String {
    let what = match (&s.target, s.access) {
        (SignalTarget::Port { .. }, Access::In) => "input".to_owned(),
        (SignalTarget::Port { .. }, Access::Out) => "output".to_owned(),
        (SignalTarget::Port { .. }, _) => "inout".to_owned(),
        (SignalTarget::Probe { module, .. }, Access::PublicRw) => {
            format!("probe in `{module}`, read-write")
        }
        (SignalTarget::Probe { module, .. }, _) => format!("probe in `{module}`, read-only"),
    };
    format!(
        "/// `{}`: {what}, {} bit{}.",
        s.name,
        s.width,
        if s.width == 1 { "" } else { "s" }
    )
}

fn emit_dut(w: &mut Writer, lowered: &Lowered) {
    w.line(format!(
        "/// The signals of model `{}`: its ports in declaration order, then its probes.",
        lowered.top
    ));
    w.line(derive(&["Clone", "Copy", "Debug"]));
    w.open("pub struct Dut {");
    for field in &lowered.fields {
        match field {
            DutField::Signal { name, slot } => {
                let s = &lowered.signals[*slot as usize];
                let (h, _) = handle(s.access);
                w.line(signal_doc(s));
                w.line(format!("pub {name}: {RT}::{h}<{}>,", render(&s.ty)));
            }
            DutField::Bundle { name, bundle, .. } => {
                let b = &lowered.bundles[*bundle];
                w.line(format!("/// Interface port `{name}` (`{}`).", b.sv_name));
                w.line(format!("pub {name}: {},", b.name));
            }
        }
    }
    w.close("}");
    w.line("");
    w.open("impl Dut {");
    w.line("/// Hash of the IR and configuration this code was generated from; the model's");
    w.line("/// vtable carries the same value.");
    w.line(format!(
        "pub const IR_HASH: {} = {};",
        prim("u64"),
        hex(u128::from(lowered.ir_hash))
    ));
    w.line("");
    emit_signal_table(w, lowered);
    // The user's module: an interface-ported DUT's parameters are its own, not the
    // generated wrapper's (which has none).
    let declared_in = lowered.wrapper.as_ref().map_or(&lowered.top, |w| &w.dut);
    for c in &lowered.dut_params {
        let (ty, expr) = const_parts(&c.value, "");
        w.line("");
        w.line(format!("/// Parameter `{}` of `{declared_in}`.", c.sv_name));
        w.line(format!("pub const {}: {ty} = {expr};", c.name));
    }
    w.line("");
    emit_dut_bind(w, lowered);
    w.close("}");
}

/// `Dut::__bind`: one `Binder` call per field, in field order.
fn emit_dut_bind(w: &mut Writer, lowered: &Lowered) {
    w.line("#[doc(hidden)]");
    w.open(format!(
        "pub fn __bind(binder: &mut impl {RT}::Binder) -> Self {{"
    ));
    w.open("Self {");
    for field in &lowered.fields {
        match field {
            DutField::Signal { name, slot } => {
                let (_, method) = handle(lowered.signals[*slot as usize].access);
                w.line(format!(
                    "{name}: {RT}::Binder::{method}(binder, &Self::SIGNALS[{slot}]),"
                ));
            }
            DutField::Bundle {
                name,
                bundle,
                first_slot,
            } => {
                let b = &lowered.bundles[*bundle];
                let end = *first_slot as usize + b.members.len();
                w.line(format!(
                    "{name}: {}::__bind(binder, &Self::SIGNALS[{first_slot}..{end}]),",
                    b.name
                ));
            }
        }
    }
    w.close("}");
    w.close("}");
}

/// `Dut::SIGNALS`.
fn emit_signal_table(w: &mut Writer, lowered: &Lowered) {
    w.line("/// Every signal, indexed by slot.");
    w.open(format!(
        "pub const SIGNALS: &'static [{RT}::SignalMeta] = &["
    ));
    for s in &lowered.signals {
        w.open(format!("{RT}::SignalMeta {{"));
        w.line(format!("name: {:?},", s.name));
        w.line(format!("slot: {},", s.slot));
        w.line(format!("width: {},", s.width));
        w.line(format!("storage: {},", storage_meta(&s.storage)));
        w.line(format!("access: {RT}::Access::{:?},", s.access));
        w.close("},");
    }
    w.close("];");
}

#[cfg(test)]
mod tests {
    use super::{grouped, hex};

    #[test]
    fn long_literals_are_grouped() {
        assert_eq!(
            grouped("633825300114114700748351602689", 3),
            "633_825_300_114_114_700_748_351_602_689"
        );
        assert_eq!(grouped("-12345", 3), "-12_345");
        assert_eq!(grouped("1234", 3), "1234");
        assert_eq!(grouped("true", 3), "true");
        assert_eq!(hex(0x5878_9409_5b07_5e21), "0x5878_9409_5b07_5e21");
        assert_eq!(hex(0x5a), "0x5a");
        assert_eq!(hex(0x12345), "0x1_2345");
    }
}
