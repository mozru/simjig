//! The layout-check SystemVerilog module (DECISION.md §1, "Layout check").
//!
//! For every generated type, the module checks at elaboration time, under the same flags
//! as the model build, that Verilator agrees with the IR the Rust code was generated from:
//! - `$bits(T)` equals the IR width;
//! - each struct or union member sits exactly at its IR bits: a value with ones at the
//!   member's IR range reads all ones through the member, and its complement reads zero;
//! - each enum constant has its IR value.
//!
//! Anonymous and module-local aggregates are declared as local typedefs at the top of the
//! module and checked through those names (see `lower/sv.rs` for why).
//!
//! A mismatch reaches `$fatal` in a generate block. Verilator reports an elaboration-time
//! `$fatal` as the `USERFATAL` warning, so the check must run with
//! [`LAYOUT_CHECK_FLAGS`]: under `-Wno-fatal` it would pass silently.

use svtypes::literal::Literal;

use super::writer::Writer;
use super::{LayoutCheck, Lowered};

/// Flags that make the check fail on a mismatch: lint only (elaboration is enough), and
/// `USERFATAL` as an error even under `-Wno-fatal`. Pass them with the model's own flags
/// and sources, and `--top-module` set to [`Layout::module`](super::Layout::module).
pub const LAYOUT_CHECK_FLAGS: &[&str] = &["--lint-only", "-Werror-USERFATAL"];

/// A sized literal with ones in bits `lsb .. lsb + width` of a `total`-bit value.
fn mask(total: u32, lsb: u32, width: u32) -> String {
    let mut words = vec![0u64; total.div_ceil(64) as usize];
    for bit in lsb..lsb + width {
        words[(bit / 64) as usize] |= 1 << (bit % 64);
    }
    // The mask lies within `total` bits by construction, so the literal is canonical.
    Literal::new(total, false, words).map_or_else(|_| format!("{total}'h0"), |l| l.to_string())
}

/// Emits the layout-check module for `lowered`.
#[must_use]
pub fn emit_layout_check(lowered: &Lowered) -> String {
    let mut w = Writer::new("  ");
    w.line(format!(
        "// @generated by simjig-build from the IR of `{}` ({}). Do not edit.",
        lowered.top, lowered.producer
    ));
    w.line(
        "// Elaborate with -Werror-USERFATAL: a $fatal below means the IR and Verilator disagree.",
    );
    w.open(format!("module {};", lowered.layout.module));
    for t in &lowered.layout.typedefs {
        w.line(format!("typedef {} {};", t.decl, t.name));
    }
    for (i, check) in lowered.layout.checks.iter().enumerate() {
        emit_check(&mut w, i, check);
    }
    w.close("endmodule");
    w.finish()
}

fn fatal(w: &mut Writer, cond: &str, label: &str, msg: &str) {
    w.open(format!("if ({cond}) begin : {label}"));
    w.line(format!("$fatal(1, \"simjig layout check: {msg}\");"));
    w.close("end");
}

fn emit_check(w: &mut Writer, i: usize, check: &LayoutCheck) {
    let (ty, width) = (&check.sv_type, check.width);
    // Names never hold a quote; the replacement only keeps the message literal intact.
    let shown = check.sv_name.replace('"', "'");
    w.line("");
    w.line(format!("// {shown}"));
    fatal(
        w,
        &format!("$bits({ty}) != {width}"),
        &format!("g_{i}_bits"),
        &format!("$bits({shown}) differs from the IR width {width}"),
    );
    for (j, m) in check.members.iter().enumerate() {
        let ones = mask(width, m.lsb, m.width);
        let zero = format!("{}'h0", m.width);
        let all = mask(m.width, 0, m.width);
        let (p, n) = (format!("P_{i}_{j}"), format!("N_{i}_{j}"));
        w.line(format!("localparam {ty} {p} = {ones};"));
        w.line(format!("localparam {ty} {n} = ~{ones};"));
        let mw = m.width;
        let name = &m.sv_name;
        fatal(
            w,
            &format!(
                "$bits({p}.{name}) != {mw} || {mw}'({p}.{name}) != {all} || {mw}'({n}.{name}) != {zero}"
            ),
            &format!("g_{i}_{j}"),
            &format!(
                "member {name} of {shown} is not bits [{}:{}] as in the IR",
                m.lsb + m.width - 1,
                m.lsb
            ),
        );
    }
    for (j, v) in check.values.iter().enumerate() {
        fatal(
            w,
            &format!("{} != {}", v.sv_expr, v.literal),
            &format!("g_{i}_v{j}"),
            &format!("{} differs from the IR value {}", v.sv_expr, v.literal),
        );
    }
}
