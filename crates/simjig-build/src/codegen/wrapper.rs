//! SystemVerilog for interface-ported DUTs: the flat-port wrapper and the
//! elaboration-only top that lets the IR be read before the wrapper exists.
//!
//! The build runs Verilator's JSON pass twice for such a DUT:
//! 1. on [`emit_elab_top`]'s module, which instantiates the bound interfaces and the DUT
//!    without ports, to learn the DUT's ports and the interfaces' modports;
//! 2. on [`emit_wrapper`]'s module (planned by [`lower_wrapper`](super::lower_wrapper)),
//!    which is the model top, so the IR has the C++ member of every flat port.
//!
//! Neither module declares a `timeunit`: each waives `TIMESCALEMOD` for itself
//! ([`TIME_WAIVER`]) instead, so it takes the design's unit, whether or not the user's
//! units declare one.

use svtypes::ir::Direction;

use super::writer::Writer;
use super::{DUT_INSTANCE, IfaceTop, Wrapper, WrapperPort, elab_module};

/// The lines around a generated module that waive Verilator's `TIMESCALEMOD` for it.
///
/// IEEE 1800-2023 §3.14.2.3: once one unit declares a time unit, every unit must, and
/// Verilator 5.052 stops on a module without one. A generated module cannot know the
/// user's units, and a `timeunit` of its own would fail the other way when they declare
/// none (checked against 5.052). Waived, Verilator gives it the unit of the highest
/// module that declares one, the DUT's (`V3LinkLevel::timescaling`), and it adds no
/// `timeprecision`, so the design's precision is the user's. The waiver covers only this
/// module: a user unit missing its `timeunit` still stops the build.
const TIME_WAIVER: [&str; 2] = [
    "// verilator lint_off TIMESCALEMOD",
    "// verilator lint_on TIMESCALEMOD",
];

/// `#(.A(x), .B(y)) ` or nothing.
fn param_list(params: &[(String, String)]) -> String {
    if params.is_empty() {
        return String::new();
    }
    let list: Vec<String> = params.iter().map(|(n, v)| format!(".{n}({v})")).collect();
    format!("#({}) ", list.join(", "))
}

fn dir_keyword(dir: Direction) -> &'static str {
    match dir {
        Direction::Input => "input ",
        Direction::Output => "output",
        Direction::Inout => "inout ",
    }
}

/// Emits the elaboration-only top for `config`: each bound interface and the DUT, with
/// the interface ports connected and every data port left open.
#[must_use]
pub fn emit_elab_top(config: &IfaceTop) -> String {
    let mut w = Writer::new("  ");
    w.line(format!(
        "// @generated by simjig-build: elaboration-only top for `{}`, read by the JSON pass. Do not edit.",
        config.dut
    ));
    w.line(TIME_WAIVER[0]);
    w.open(format!("module {};", elab_module(&config.dut)));
    for b in &config.bindings {
        w.line(format!(
            "{} {}{} ();",
            b.interface,
            param_list(&b.params),
            b.port
        ));
    }
    let conns: Vec<String> = config
        .bindings
        .iter()
        .map(|b| format!(".{0}({0})", b.port))
        .collect();
    w.line(format!(
        "{} {}{DUT_INSTANCE} ({});",
        config.dut,
        param_list(&config.params),
        conns.join(", ")
    ));
    w.close("endmodule");
    w.line(TIME_WAIVER[1]);
    w.finish()
}

/// Emits the flat-port wrapper.
#[must_use]
pub fn emit_wrapper(wrapper: &Wrapper) -> String {
    let mut w = Writer::new("  ");
    w.line(format!(
        "// @generated by simjig-build: flat-port top for `{}`. Do not edit.",
        wrapper.dut
    ));
    w.line(TIME_WAIVER[0]);
    w.open(format!("module {} (", wrapper.module));
    emit_ports(&mut w, &wrapper.ports);
    w.close(");");
    w.open("");
    for iface in &wrapper.ifaces {
        let conns: Vec<String> = iface
            .port_conns
            .iter()
            .map(|(p, f)| format!(".{p}({f})"))
            .collect();
        w.line(format!(
            "{} {}{} ({});",
            iface.interface,
            param_list(&iface.params),
            iface.instance,
            conns.join(", ")
        ));
    }
    for iface in &wrapper.ifaces {
        for (lhs, rhs) in &iface.assigns {
            w.line(format!("assign {lhs} = {rhs};"));
        }
    }
    w.line("");
    let mut conns: Vec<String> = wrapper
        .dut_conns
        .iter()
        .map(|(p, f)| format!(".{p}({f})"))
        .collect();
    conns.extend(
        wrapper
            .ifaces
            .iter()
            .map(|i| format!(".{0}({0}.{1})", i.instance, i.modport)),
    );
    w.open(format!(
        "{} {}{DUT_INSTANCE} (",
        wrapper.dut,
        param_list(&wrapper.dut_params)
    ));
    for (i, c) in conns.iter().enumerate() {
        let sep = if i + 1 == conns.len() { "" } else { "," };
        w.line(format!("{c}{sep}"));
    }
    w.close(");");
    w.close("endmodule");
    w.line(TIME_WAIVER[1]);
    w.finish()
}

/// The wrapper's port list, one port a line.
fn emit_ports(w: &mut Writer, ports: &[WrapperPort]) {
    for (i, p) in ports.iter().enumerate() {
        let sep = if i + 1 == ports.len() { "" } else { "," };
        let mut line = format!(
            "{} {} {}",
            dir_keyword(p.dir),
            port_type(&p.packed, p.dir),
            p.name
        );
        if !p.unpacked.is_empty() {
            line.push(' ');
            line.push_str(&p.unpacked);
        }
        w.line(format!("{line}{sep}"));
    }
}

/// An `inout` port must be a net (IEEE 1800-2023 §23.2.2.3): `logic` becomes `wire logic`.
fn port_type(packed: &str, dir: Direction) -> String {
    if dir == Direction::Inout {
        format!("wire {packed}")
    } else {
        packed.to_owned()
    }
}
