//! The Verilator control file: `public_flat_rd`/`public_flat_rw` for probed signals only.
//!
//! Logic that reads a public signal is re-evaluated on every `eval()`, so the public set
//! stays minimal: ports need no line (they are always accessible), and each probe gets
//! exactly the access it asked for. Verilator matches `-module` by the declared module
//! name, so one line covers every instance of that module.

use super::writer::Writer;
use super::{Access, Lowered, SignalTarget};

/// Emits the `.vlt` file for `lowered`.
#[must_use]
pub fn emit_vlt(lowered: &Lowered) -> String {
    let mut w = Writer::new("  ");
    w.line("`verilator_config");
    w.line(format!(
        "// @generated by simjig-build from the IR of `{}` ({}). Do not edit.",
        lowered.top, lowered.producer
    ));
    let mut lines: Vec<String> = Vec::new();
    for s in &lowered.signals {
        let SignalTarget::Probe { module, var, .. } = &s.target else {
            continue;
        };
        let option = if s.access == Access::PublicRw {
            "public_flat_rw"
        } else {
            "public_flat_rd"
        };
        let line = format!("{option} -module \"{module}\" -var \"{var}\"");
        if !lines.contains(&line) {
            lines.push(line);
        }
    }
    for line in lines {
        w.line(line);
    }
    w.finish()
}
