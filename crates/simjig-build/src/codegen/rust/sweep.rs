//! The sweep module: the runtime traits a generic body needs (re-exported, so one
//! `use <sweep>::*;` is the body's only import), what a [`LoweredSweep`]'s members share,
//! its traits (`Ports`, bundle traits, fields traits), and each member as a submodule
//! with its trait implementations.
//!
//! The file sits next to its members' files in `OUT_DIR/simjig/` and includes each one
//! with a relative `include!("<member>.rs")`, which Rust resolves against the including
//! file's directory, so `include_dut!(<sweep>)` brings in the whole sweep.

use super::super::writer::Writer;
use super::super::{
    Access, AssocBound, AssocType, ConstValue, FieldsTrait, LoweredSweep, MethodKind, PortsTrait,
    RustType, TraitType,
};
use super::{RT, const_parts, emit_bundle, emit_package, handle, items, render};

/// Emits the sweep module of `sweep`.
#[must_use]
pub fn emit_sweep(sweep: &LoweredSweep) -> String {
    let mut w = Writer::new("    ");
    let names: Vec<String> = sweep
        .members
        .iter()
        .map(|m| format!("`{}`", m.name))
        .collect();
    w.line(format!(
        "// @generated by simjig-build: sweep `{}` of `{}` ({}). Do not edit.",
        sweep.name,
        sweep.dut,
        names.join(", ")
    ));
    emit_runtime_traits(&mut w, sweep);
    for item in &sweep.items {
        w.line("");
        items::emit_item(&mut w, item);
    }
    for group in &sweep.packages {
        w.line("");
        emit_package(&mut w, group);
    }
    for bundle in &sweep.bundles {
        w.line("");
        emit_bundle(&mut w, bundle);
    }
    w.line("");
    emit_ports_doc(&mut w, sweep, &names);
    emit_trait(&mut w, &sweep.ports);
    for t in &sweep.bundle_traits {
        w.line("");
        w.line(format!(
            "/// The signals of interface modport `{}` that the bundles of every configuration have.",
            t.sv_name
        ));
        emit_trait_docs_tail(&mut w, t);
        emit_trait(&mut w, t);
    }
    for t in &sweep.fields_traits {
        w.line("");
        emit_fields_trait(&mut w, t);
    }
    for (i, member) in sweep.members.iter().enumerate() {
        w.line("");
        let params: Vec<String> = member
            .params
            .iter()
            .filter_map(|c| shown(&c.value).map(|v| format!("`{}` = {v}", c.sv_name)))
            .collect();
        let with = if params.is_empty() {
            String::new()
        } else {
            format!(": {}", params.join(", "))
        };
        w.line(format!(
            "/// Configuration `{}` of `{}`{with}.",
            member.name, sweep.dut
        ));
        w.open(format!("pub mod {} {{", member.name));
        w.line(format!("::core::include!(\"{}.rs\");", member.name));
        w.close("}");
        for t in std::iter::once(&sweep.ports).chain(&sweep.bundle_traits) {
            w.line("");
            emit_impl(&mut w, t, i);
        }
        for t in &sweep.fields_traits {
            w.line("");
            emit_fields_impl(&mut w, t, i);
        }
    }
    w.finish()
}

/// The runtime traits a generic body needs in scope, re-exported so that one
/// `use <sweep>::*;` brings them with the sweep's own traits.
fn emit_runtime_traits(w: &mut Writer, sweep: &LoweredSweep) {
    let paths: Vec<&str> = sweep
        .runtime_traits
        .iter()
        .map(|n| {
            if n == "Packed" {
                "bits::Packed"
            } else {
                n.as_str()
            }
        })
        .collect();
    if paths.is_empty() {
        return;
    }
    w.line("");
    w.line("/// The runtime traits a test body generic over this sweep calls methods of, so that");
    w.line(format!(
        "/// one `use {}::*;` brings them into scope with the sweep's own traits.",
        sweep.name
    ));
    w.line("#[doc(no_inline)]");
    w.line(format!("pub use {RT}::{{{}}};", paths.join(", ")));
}

/// A parameter value as the member docs show it, for the plain kinds.
fn shown(value: &ConstValue) -> Option<String> {
    match value {
        ConstValue::Int { value, .. } => Some(value.clone()),
        ConstValue::Str(s) => Some(format!("{s:?}")),
        ConstValue::Real(text) => Some(text.clone()),
        _ => None,
    }
}

fn emit_ports_doc(w: &mut Writer, sweep: &LoweredSweep, names: &[String]) {
    w.line(format!(
        "/// The signals of `{}` that every configuration of sweep `{}` has ({}), for a test",
        sweep.dut,
        sweep.name,
        names.join(", ")
    ));
    w.line(format!(
        "/// body written once: `async fn t<D: {}::{}>(dut: D)`. Each configuration's `Dut`",
        sweep.name, sweep.ports.name
    ));
    w.line("/// implements it; each method returns the `Dut` field of the same name.");
    emit_trait_docs_tail(w, &sweep.ports);
}

/// The docs every trait ends with: associated types and left-out fields.
fn emit_trait_docs_tail(w: &mut Writer, t: &PortsTrait) {
    if !t.types.is_empty() {
        w.line("///");
        w.line("/// A signal whose type differs between configurations has an associated type;");
        w.line("/// signals whose types agree in every configuration share one.");
    }
    if !t.omitted.is_empty() {
        let list: Vec<String> = t.omitted.iter().map(|n| format!("`{n}`")).collect();
        w.line("///");
        w.line(format!(
            "/// Left out, as not every configuration has them alike: {}.",
            list.join(", ")
        ));
    }
}

fn emit_trait(w: &mut Writer, t: &PortsTrait) {
    w.open(format!(
        "pub trait {}: ::core::marker::Copy + ::core::fmt::Debug + 'static {{",
        t.name
    ));
    for c in &t.consts {
        let (ty, _) = const_parts(&c.value, "");
        w.line(format!("/// Parameter `{}` of `{}`.", c.sv_name, t.sv_name));
        w.line(format!("const {}: {ty};", c.name));
    }
    for a in &t.types {
        w.line(assoc_doc(a, &t.impls));
        w.line(format!("type {}{};", a.name, bound(a, &t.types)));
    }
    for m in &t.methods {
        let renamed = if m.name == m.field {
            String::new()
        } else {
            format!(
                " (`{}` here: a supertrait has a method `{}`)",
                m.name, m.field
            )
        };
        w.line(format!("/// `{}`{}{renamed}.", m.sv_name, what(&m.kind)));
        w.line(format!(
            "fn {}(self) -> {};",
            m.name,
            return_type(t, &m.kind)
        ));
    }
    w.close("}");
}

/// The bound of `a` as written after its name (`: Vector`, `: BeatIfSinkPorts<Beat =
/// Self::Beat>`), `types` being its trait's.
fn bound(a: &AssocType, types: &[AssocType]) -> String {
    match &a.bound {
        AssocBound::Vector => format!(": {RT}::Vector"),
        AssocBound::Value => format!(": {RT}::Value"),
        AssocBound::Trait(name) if a.equals.is_empty() => format!(": {name}"),
        AssocBound::Trait(name) => {
            let fixed: Vec<String> = a
                .equals
                .iter()
                .map(|(inner, i)| format!("{inner} = Self::{}", types[*i].name))
                .collect();
            format!(": {name}<{}>", fixed.join(", "))
        }
        AssocBound::None => String::new(),
    }
}

/// The doc line of an associated type: who uses it, and what it is in each member.
fn assoc_doc(a: &AssocType, impls: &[String]) -> String {
    let users: Vec<String> = a.users.iter().map(|u| format!("`{u}`")).collect();
    let per: Vec<String> = a
        .per_impl
        .iter()
        .zip(impls)
        .map(|(ty, path)| format!("`{}` in `{}`", short(ty), member_of(path)))
        .collect();
    format!("/// The type of {}: {}.", users.join(", "), per.join(", "))
}

/// A [`FieldsTrait`]: a getter per field, `new` and a setter per field.
fn emit_fields_trait(w: &mut Writer, t: &FieldsTrait) {
    w.line(format!(
        "/// The fields of SystemVerilog `{}`, a packed struct whose field types differ between",
        t.sv_name
    ));
    w.line(
        "/// configurations: a getter per field, `new` from every field and `with_<field>`, for a",
    );
    w.line("/// test body generic over the sweep. Each configuration's struct implements it.");
    w.open(format!("pub trait {}: {RT}::Value {{", t.name));
    for a in &t.types {
        w.line(assoc_doc(a, &t.impls));
        w.line(format!("type {}{};", a.name, bound(a, &t.types)));
    }
    for f in &t.fields {
        w.line(format!("/// Field `{}`.", f.sv_name));
        w.line(format!(
            "fn {}(self) -> {};",
            f.getter,
            field_type(t, &f.ty)
        ));
    }
    w.line("/// The value with these fields, in declaration order (the first most significant).");
    w.line("#[must_use]");
    w.line(format!("fn new({}) -> Self;", new_params(t)));
    for f in &t.fields {
        w.line(format!("/// `self` with field `{}` replaced.", f.sv_name));
        w.line("#[must_use]");
        w.line(format!(
            "fn {}(self, {}: impl ::core::convert::Into<{}>) -> Self;",
            f.setter,
            f.name,
            field_type(t, &f.ty)
        ));
    }
    w.close("}");
}

/// The impl of `t` for member `i`'s struct.
fn emit_fields_impl(w: &mut Writer, t: &FieldsTrait, i: usize) {
    w.open(format!("impl {} for {} {{", t.name, t.impls[i]));
    for a in &t.types {
        w.line(format!("type {} = {};", a.name, render(&a.per_impl[i])));
    }
    for f in &t.fields {
        w.line(format!(
            "fn {}(self) -> {} {{ self.{} }}",
            f.getter,
            field_type(t, &f.ty),
            f.name
        ));
    }
    let inits: Vec<String> = t
        .fields
        .iter()
        .map(|f| format!("{0}: {0}.into()", f.name))
        .collect();
    w.line(format!(
        "fn new({}) -> Self {{ Self {{ {} }} }}",
        new_params(t),
        inits.join(", ")
    ));
    for f in &t.fields {
        w.line(format!(
            "fn {}(mut self, {1}: impl ::core::convert::Into<{2}>) -> Self {{ self.{1} = {1}.into(); self }}",
            f.setter,
            f.name,
            field_type(t, &f.ty)
        ));
    }
    w.close("}");
}

/// `new`'s parameters: one per field, taking anything that converts into it.
fn new_params(t: &FieldsTrait) -> String {
    let params: Vec<String> = t
        .fields
        .iter()
        .map(|f| {
            format!(
                "{}: impl ::core::convert::Into<{}>",
                f.name,
                field_type(t, &f.ty)
            )
        })
        .collect();
    params.join(", ")
}

/// A field's type in a [`FieldsTrait`]'s signatures.
fn field_type(t: &FieldsTrait, ty: &TraitType) -> String {
    match ty {
        TraitType::Concrete(ty) => render(ty),
        TraitType::Assoc(i) => format!("Self::{}", t.types[*i].name),
    }
}

/// `: input` and the like, for a method's doc.
fn what(kind: &MethodKind) -> &'static str {
    match kind {
        MethodKind::Signal { access, .. } => match access {
            Access::In => ": input",
            Access::Out => ": output",
            Access::InOut => ": inout",
            Access::PublicRd => ": probe, read-only",
            Access::PublicRw => ": probe, read-write",
        },
        MethodKind::Bundle(_) => ": interface port",
    }
}

fn trait_type(t: &PortsTrait, ty: &TraitType) -> String {
    match ty {
        TraitType::Concrete(ty) => render(ty),
        TraitType::Assoc(i) => format!("Self::{}", t.types[*i].name),
    }
}

fn return_type(t: &PortsTrait, kind: &MethodKind) -> String {
    match kind {
        MethodKind::Signal { access, ty } => {
            let (h, _) = handle(*access);
            format!("{RT}::{h}<{}>", trait_type(t, ty))
        }
        MethodKind::Bundle(ty) => trait_type(t, ty),
    }
}

/// The impl of `t` for its implementation `i`.
fn emit_impl(w: &mut Writer, t: &PortsTrait, i: usize) {
    let path = &t.impls[i];
    w.open(format!("impl {} for {path} {{", t.name));
    for c in &t.consts {
        let (ty, _) = const_parts(&c.value, "");
        w.line(format!("const {}: {ty} = {path}::{};", c.name, c.name));
    }
    for a in &t.types {
        w.line(format!("type {} = {};", a.name, render(&a.per_impl[i])));
    }
    for m in &t.methods {
        w.line(format!(
            "fn {}(self) -> {} {{ self.{} }}",
            m.name,
            return_type(t, &m.kind),
            m.field
        ));
    }
    w.close("}");
}

/// The member module of an implementing type's path (`small::Dut` is `small`).
fn member_of(path: &str) -> &str {
    path.split("::").next().unwrap_or(path)
}

/// A type as the docs show it: without the runtime's path.
fn short(ty: &RustType) -> String {
    match ty {
        RustType::Bit => "Bit".to_owned(),
        RustType::Bits(n) => format!("Bits<{n}>"),
        RustType::WideBits { width, words } => format!("WideBits<{width}, {words}>"),
        RustType::Named(n) => n.clone(),
        RustType::Array(elem, len) => format!("[{}; {len}]", short(elem)),
    }
}
